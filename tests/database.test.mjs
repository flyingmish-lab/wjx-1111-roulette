test('migration preserves data, restricts roles, enforces limits and aggregates beyond 1000 rows',async()=>{
  const db=new PGlite();
  try {
    await db.exec(fixture);
    const migration=fs.readFileSync('supabase/migrations/202611190001_browser_admin_auth.sql','utf8');
    await db.exec(migration);
    // Applying the same migration again must not erase rows or reset state.
    await db.exec(migration);
    assert.equal((await db.query('select count(*)::int as n from wjx_test_spins')).rows[0].n,1);
    assert.equal((await db.query('select test_mode from roulette_settings')).rows[0].test_mode,true);
    for(const role of ['anon','authenticated']) {
      for(const table of ['wjx_admin_sessions','wjx_admin_login_attempts','roulette_settings','roulette_prize_chances','wjx_participants','wjx_spins','wjx_test_spins']) {
        const {rows}=await db.query(`select has_table_privilege($1,$2,'SELECT') as r, has_table_privilege($1,$2,'INSERT') as w`,[role,table]);
        assert.deepEqual(rows[0],{r:false,w:false});
      }
      for(const fn of ['wjx_consume_admin_login_attempt()','wjx_admin_prize_stats()','wjx_save_spin(bigint,date,text)','wjx_save_test_spin(bigint,date,text)']) {
        assert.equal((await db.query(`select has_function_privilege($1,$2,'EXECUTE') as x`,[role,fn])).rows[0].x,false);
      }
    }
    assert.equal((await db.query(`select has_function_privilege('service_role','wjx_save_test_spin(bigint,date,text)','EXECUTE') as x`)).rows[0].x,false);
    assert.equal((await db.query("select bool_and(c.relrowsecurity) as enabled from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind='r'")).rows[0].enabled,true);
    await db.exec('set role service_role');
    const attempts=await Promise.all(Array.from({length:30},()=>db.query('select * from wjx_consume_admin_login_attempt()')));
    assert.equal(attempts.filter(r=>r.rows[0].allowed).length,10);
    assert.ok(attempts[10].rows[0].retry_after>0);
    await db.exec(`update wjx_admin_login_attempts set window_started_at=now()-interval '16 minutes' where client_id='shared-admin-v1'`);
    assert.equal((await db.query('select * from wjx_consume_admin_login_attempt()')).rows[0].allowed,true);
    const {rows:[{day}]}=await db.query(`select (clock_timestamp() at time zone 'Europe/Moscow')::date::text as day`);
    // Postgres advisory lock implementation is exercised by each invocation.
    for(const id of [221535678,382749857,123456789]) {
      for(let n=1;n<=3;n++) {
        const result=await db.query('select * from wjx_save_spin($1,$2,$3)',[id,day,'Без выигрыша']);
        assert.deepEqual(result.rows[0],{spin_number:n,spins_remaining:3-n});
      }
      await assert.rejects(db.query('select * from wjx_save_spin($1,$2,$3)',[id,day,'Без выигрыша']),/Daily spin limit/);
    }
    await db.exec(`update roulette_settings set event_start='2099-01-01'`);
    await assert.rejects(db.query('select * from wjx_save_spin($1,$2,$3)',[999,day,'Без выигрыша']),/Event is not active/);
    await db.exec(`update roulette_settings set event_start='2000-01-01'`);
    await assert.rejects(db.query('select * from wjx_save_spin($1,$2,$3)',[999,'2001-01-01','Без выигрыша']),/Event is not active/);
    await assert.rejects(db.query('select * from wjx_save_spin($1,$2,$3)',[999,day,'Injected prize']),/Invalid prize/);
    await db.exec(`insert into wjx_spins(telegram_id,spin_date,spin_number,prize) select 999,current_date,1,'Без выигрыша' from generate_series(1,1200)`);
    const stats=(await db.query('select wjx_admin_prize_stats() as result')).rows[0].result;
    assert.equal(stats.prizes[0].realWins,1209);
    assert.equal(stats.prizes[0].testWins,1);
    assert.equal(stats.history.length,50);
  } finally { await db.close(); }
});

